#!/usr/bin/env python3
"""
gen_ral.py — generate tb/ral/boom_csr_reg_block.sv (UVM register model of the
CSRFile) from sim/csr_spec.py. Same idea as ralgen / IP-XACT flows: the spec is
the single source of truth, the SystemVerilog is derived.

    python3 gen_ral.py
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from csr_spec import REGS, ILLEGAL_ADDRS

HERE = os.path.dirname(os.path.abspath(__file__))
OUT  = os.path.join(HERE, '..', 'tb', 'ral', 'boom_csr_reg_block.sv')

def cls(r): return 'boom_csr_reg_' + r['name']

L = []
w = L.append
w('//=============================================================================')
w('// boom_csr_reg_block.sv — GENERATED by sim/gen_ral.py from sim/csr_spec.py')
w('//-----------------------------------------------------------------------------')
w('// UVM register model (RAL) of rocket-chip CSRFile as elaborated in the BOOM')
w('// core: %d registers. Field widths / reset values / WARL rules were measured' % len(REGS))
w('// on the RTL (sim/smoke "CSR characterisation"). Do not edit — edit the spec.')
w('//=============================================================================')
w('')
for r in REGS:
    w('class %s extends uvm_reg;' % cls(r))
    w('  `uvm_object_utils(%s)' % cls(r))
    for f in r['fields']:
        w('  rand uvm_reg_field %s;' % f[0])
    w('  function new(string name = "%s"); super.new(name, 64, UVM_NO_COVERAGE); endfunction' % r['name'])
    w('  virtual function void build();')
    for name, lsb, width, access, reset, vol in r['fields']:
        w('    %s = uvm_reg_field::type_id::create("%s");' % (name, name))
        w("    %s.configure(this, %d, %d, \"%s\", %d, 64'h%x, 1, %d, 1);" % (name, width, lsb, access, vol, reset, 1 if access == 'RW' else 0))
    w('  endfunction')
    if r.get('predict') == 'satp':
        w('  // WARL on the whole register: a write with an unsupported MODE (not Bare/Sv39) is dropped entirely')
        w('  virtual function void do_predict(uvm_reg_item rw, uvm_predict_e kind = UVM_PREDICT_DIRECT, uvm_reg_byte_en_t be = -1);')
        w("    if (kind == UVM_PREDICT_WRITE && !(rw.value[0][63:60] inside {4'd0, 4'd8})) begin")
        w('      `uvm_info("RAL", $sformatf("satp write %016h dropped by hardware (MODE %0d unsupported)", rw.value[0], rw.value[0][63:60]), UVM_MEDIUM)')
        w('      return;')
        w('    end')
        w('    super.do_predict(rw, kind, be);')
        w('  endfunction')
    if r.get('predict') == 'pmpcfg':
        w('  // an entry whose L bit is set is locked until reset: its byte ignores further writes')
        w('  virtual function void do_predict(uvm_reg_item rw, uvm_predict_e kind = UVM_PREDICT_DIRECT, uvm_reg_byte_en_t be = -1);')
        w('    if (kind == UVM_PREDICT_WRITE) begin')
        w('      uvm_reg_data_t cur = get_mirrored_value();')
        w('      for (int i = 0; i < 8; i++) if (cur[8*i+7]) rw.value[0][8*i +: 8] = cur[8*i +: 8];')
        w('    end')
        w('    super.do_predict(rw, kind, be);')
        w('  endfunction')
    w('endclass')
    w('')

w('//-----------------------------------------------------------------------------')
w('class boom_csr_reg_block extends uvm_reg_block;')
w('  `uvm_object_utils(boom_csr_reg_block)')
for r in REGS:
    w('  rand %s %s;' % (cls(r), r['name']))
w('  uvm_reg_map csr_map;')
w('  function new(string name = "boom_csr_reg_block"); super.new(name, UVM_NO_COVERAGE); endfunction')
w('')
w('  virtual function void build();')
w('    // word addressing: the map address *is* the 12-bit CSR number')
w("    csr_map = create_map(\"csr_map\", 'h0, 8, UVM_LITTLE_ENDIAN, 0);")
w('    default_map = csr_map;')
for r in REGS:
    w('    %s = %s::type_id::create("%s"); %s.configure(this); %s.build();' % (r['name'], cls(r), r['name'], r['name'], r['name']))
    rights = 'RO' if all(f[3] == 'RO' for f in r['fields']) else 'RW'
    w("    csr_map.add_reg(%s, 12'h%03x, \"%s\");" % (r['name'], r['addr'], rights))
    if r.get('hdl'):
        w('    %s.add_hdl_path_slice("%s", 0, %d);' % (r['name'], r['hdl'][0], r['hdl'][1]))
    for a in r.get('attrs', []):
        w('    uvm_resource_db#(bit)::set({"REG::", %s.get_full_name()}, "%s", 1, this);' % (r['name'], a))
w('    add_hdl_path("tb_top.u_csr");')
w('    lock_model();')
w('  endfunction')
w('')
w('  // behavioural hooks (aliases, WARL legalisation, derived bits) — see boom_csr_reg_cbs.sv')
w('  virtual function void attach_callbacks();')
w('    boom_csr_alias_cbs  al;')
w('    boom_csr_warl_cbs   wl;')
for r in REGS:
    # WARL legalisation must run before the alias propagation on the same field (callbacks run in order of registration)
    for fld, kind, arg in r.get('warl', []):
        w('    wl = new("warl_%s_%s", WARL_%s, %d, %s); uvm_reg_field_cb::add(%s.%s, wl);' % (r['name'], fld, kind.upper(), arg, 'this' if kind == 'mideleg' else 'null', r['name'], fld))
    for dst, ranges in r.get('alias', []):
        rs = ', '.join("'{%d, %d, %d}" % t for t in ranges)
        w('    al = new("alias_%s_to_%s", %s, %s, \'{%s}); al.blk = this; al.by_mideleg = %d; al.attach();' % (r['name'], dst, r['name'], dst, rs, 1 if dst in ('sie', 'sip') or r['name'] in ('sie', 'sip') else 0))
w('  endfunction')
w('')
w('  // CSR numbers that must decode as illegal in this configuration')
w("  static bit [11:0] illegal_addrs[] = '{%s};" % ', '.join("12'h%03x" % a for a in ILLEGAL_ADDRS))
w('  function uvm_reg reg_by_addr(bit [11:0] a); return csr_map.get_reg_by_offset(a); endfunction')
w('endclass : boom_csr_reg_block')

os.makedirs(os.path.dirname(OUT), exist_ok=True)
open(OUT, 'w').write('\n'.join(L) + '\n')
print('wrote', OUT, '-', len(REGS), 'registers,', sum(len(r['fields']) for r in REGS), 'fields')
