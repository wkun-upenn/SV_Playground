#!/usr/bin/env python3
"""
gen_dut_glue.py — regenerate the pieces of the testbench that depend on the
exact port list of the Chisel-generated RTL:

  tb/boom_exe_uop_types.svh   packed structs uop_t / rsp_uop_t (union of all
                              io_*_uop_* ports of the three execution units)
  tb/boom_exe_dut_inst.svh    the three ALUExeUnit_1 / ALUExeUnit_2 / FPUExeUnit
                              instantiations + IssueUnitCollapsing_2 + CSRFile, wired
                              to the boom_exu_if / boom_iq_if / boom_csr_if interfaces
  dut/boom_exe_dut.f          RTL file list (subtree of the four DUT modules)

Run again whenever the RTL is re-elaborated with a different config.
"""
import re, json, os, sys, collections

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..'))
GEN  = os.environ.get('BOOM_RTL', os.path.abspath(os.path.join(ROOT, '..'))) + '/gen-collateral'
HIER = os.environ.get('BOOM_RTL', os.path.abspath(os.path.join(ROOT, '..'))) + '/meta/top_module_hierarchy.json'

UNITS = {'ALUExeUnit_1': 'alu0', 'ALUExeUnit_2': 'alu1', 'FPUExeUnit': 'fpu'}
IQ    = 'IssueUnitCollapsing_2'
CSR   = 'CSRFile'

def ports(m):
    txt = open(os.path.join(GEN, m + '.sv')).read()
    hdr = txt[txt.index('module ' + m):]
    hdr = hdr[:hdr.index(');')]
    hdr = re.sub(r'//.*', '', hdr)
    out = []
    for mm in re.finditer(r'(input|output)\s+(\[\d+:\d+\])?\s*(\w+)', hdr):
        d, w, n = mm.groups()
        out.append((d, w or '', n))
    return out

def width(w):
    return int(w.strip('[]').split(':')[0]) + 1 if w else 1

# ----------------------------------------------------------------------------
# 1. structs
# ----------------------------------------------------------------------------
allp = {m: ports(m) for m in list(UNITS) + [IQ, CSR]}
req_fields = collections.OrderedDict()
rsp_fields = collections.OrderedDict()
for m in UNITS:
    for d, w, n in allp[m]:
        if n.startswith('io_req_bits_uop_'):
            req_fields.setdefault(n[len('io_req_bits_uop_'):], w)
        mm = re.match(r'io_(iresp|ll_iresp|fresp|ll_fresp)_bits_uop_(\w+)', n)
        if mm:
            rsp_fields.setdefault(mm.group(2), w)
# IQ issue uop == full uop (same field set as dispatch)
iq_iss = collections.OrderedDict()
for d, w, n in allp[IQ]:
    mm = re.match(r'io_iss_uops_0_(\w+)', n)
    if mm: iq_iss.setdefault(mm.group(1), w)
    mm = re.match(r'io_dis_uops_0_bits_(\w+)', n)
    if mm: req_fields.setdefault(mm.group(1), w)

def struct(name, fields):
    s = ['typedef struct packed {']
    for f, w in fields.items():
        s.append('  logic %s%s;' % ((w + ' ') if w else '', f))
    s.append('} %s;' % name)
    return '\n'.join(s)

with open(os.path.join(ROOT, 'tb', 'boom_exe_uop_types.svh'), 'w') as f:
    f.write('// GENERATED by sim/gen_dut_glue.py from the RTL port lists — do not edit.\n')
    f.write('// uop_t     : every io_req_bits_uop_* / io_dis_uops_*_bits_* field (%d fields)\n' % len(req_fields))
    f.write('// rsp_uop_t : every io_*resp_bits_uop_* field (%d fields)\n\n' % len(rsp_fields))
    f.write(struct('uop_t', req_fields) + '\n\n')
    f.write(struct('rsp_uop_t', rsp_fields) + '\n')
print('uop_t fields:', len(req_fields), ' rsp_uop_t fields:', len(rsp_fields))

# ----------------------------------------------------------------------------
# 2. DUT instantiations
# ----------------------------------------------------------------------------
def exu_map(n, unit):
    """map a DUT port name to an expression on the boom_exu_if instance."""
    v = unit + '_if'
    if n == 'clock': return 'clk'
    if n == 'reset': return 'rst'
    if n == 'io_fu_types': return v + '.fu_types'
    if n == 'io_req_valid': return v + '.req_valid'
    if n == 'io_req_bits_kill': return v + '.kill_any'
    if n == 'io_req_bits_rs1_data': return v + '.rs1_data'
    if n == 'io_req_bits_rs2_data': return v + '.rs2_data'
    if n == 'io_req_bits_rs3_data': return v + '.rs3_data'
    if n.startswith('io_req_bits_uop_'): return v + '.req_uop.' + n[len('io_req_bits_uop_'):]
    if n == 'io_brupdate_b1_resolve_mask': return v + '.br_resolve_mask'
    if n == 'io_brupdate_b1_mispredict_mask': return v + '.br_mispredict_mask'
    if n == 'io_fcsr_rm': return v + '.fcsr_rm'
    m = re.match(r'io_(iresp|ll_iresp|fresp|ll_fresp)_(valid|ready)$', n)
    if m: return v + '.%s_%s' % m.groups()
    m = re.match(r'io_(iresp|ll_iresp|fresp|ll_fresp)_bits_uop_(\w+)$', n)
    if m: return v + '.%s_uop.%s' % m.groups()
    m = re.match(r'io_(iresp|ll_iresp|fresp|ll_fresp)_bits_(data|predicated)$', n)
    if m: return v + '.%s_%s' % m.groups()
    m = re.match(r'io_(iresp|ll_iresp|fresp|ll_fresp)_bits_fflags_valid$', n)
    if m: return v + '.%s_fflags_valid' % m.group(1)
    m = re.match(r'io_(iresp|ll_iresp|fresp|ll_fresp)_bits_fflags_bits_flags$', n)
    if m: return v + '.%s_fflags' % m.group(1)
    m = re.match(r'io_(iresp|ll_iresp|fresp|ll_fresp)_bits_fflags_bits_uop_rob_idx$', n)
    if m: return v + '.%s_fflags_rob_idx' % m.group(1)
    m = re.match(r'io_bypass_(\d)_valid$', n)
    if m: return v + '.bypass_valid[%s]' % m.group(1)
    m = re.match(r'io_bypass_(\d)_bits_uop_pdst$', n)
    if m: return v + '.bypass_pdst[%s]' % m.group(1)
    m = re.match(r'io_bypass_(\d)_bits_uop_dst_rtype$', n)
    if m: return v + '.bypass_dst_rtype[%s]' % m.group(1)
    m = re.match(r'io_bypass_(\d)_bits_data$', n)
    if m: return v + '.bypass_data[%s]' % m.group(1)
    m = re.match(r'io_brinfo_uop_(\w+)$', n)
    if m: return v + '.brinfo_uop_' + m.group(1)
    m = re.match(r'io_brinfo_(\w+)$', n)
    if m: return v + '.brinfo_' + m.group(1)
    m = re.match(r'io_get_ftq_pc_(\w+)$', n)
    if m: return v + '.ftq_' + m.group(1)
    raise RuntimeError('unmapped port ' + n)

def iq_map(n):
    v = 'iq_if'
    if n == 'clock': return 'clk'
    if n == 'reset': return 'rst'
    m = re.match(r'io_dis_uops_(\d)_(valid|ready)$', n)
    if m: return v + '.dis_%s[%s]' % (m.group(2), m.group(1))
    m = re.match(r'io_dis_uops_(\d)_bits_(\w+)$', n)
    if m: return v + '.dis_uop[%s].%s' % (m.group(1), m.group(2))
    m = re.match(r'io_iss_valids_(\d)$', n)
    if m: return v + '.iss_valid[%s]' % m.group(1)
    m = re.match(r'io_iss_uops_(\d)_(\w+)$', n)
    if m: return v + '.iss_uop[%s].%s' % (m.group(1), m.group(2))
    m = re.match(r'io_wakeup_ports_(\d)_valid$', n)
    if m: return v + '.wakeup_valid[%s]' % m.group(1)
    m = re.match(r'io_wakeup_ports_(\d)_bits_pdst$', n)
    if m: return v + '.wakeup_pdst[%s]' % m.group(1)
    m = re.match(r'io_spec_ld_wakeup_(\d)_valid$', n)
    if m: return v + '.spec_ld_wakeup_valid[%s]' % m.group(1)
    m = re.match(r'io_spec_ld_wakeup_(\d)_bits$', n)
    if m: return v + '.spec_ld_wakeup_pdst[%s]' % m.group(1)
    m = re.match(r'io_fu_types_(\d)$', n)
    if m: return v + '.fu_types[%s]' % m.group(1)
    if n == 'io_brupdate_b1_resolve_mask': return v + '.br_resolve_mask'
    if n == 'io_brupdate_b1_mispredict_mask': return v + '.br_mispredict_mask'
    if n == 'io_flush_pipeline': return v + '.flush_pipeline'
    if n == 'io_ld_miss': return v + '.ld_miss'
    raise RuntimeError('unmapped IQ port ' + n)

out = ['// GENERATED by sim/gen_dut_glue.py — DUT instantiations wired to the interfaces.', '']
for m, unit in UNITS.items():
    out.append('  %s u_%s (' % (m, unit))
    conns = ['    .%s(%s)' % (n, exu_map(n, unit)) for d, w, n in allp[m]]
    out.append(',\n'.join(conns))
    out.append('  );\n')
out.append('  %s u_iq (' % IQ)
out.append(',\n'.join('    .%s(%s)' % (n, iq_map(n)) for d, w, n in allp[IQ]))
out.append('  );\n')

def csr_map(d, w, n):
    v = 'csr_if'
    if n in ('clock', 'io_ungated_clock'): return 'clk'
    if n == 'reset': return 'rst'
    m = re.match(r'io_interrupts_(\w+)$', n)
    if m: return v + '.irq_' + m.group(1)
    if n == 'io_hartid': return v + '.hartid'
    m = re.match(r'io_rw_(\w+)$', n)
    if m: return v + '.rw_' + m.group(1)
    m = re.match(r'io_decode_0_(\w+)$', n)
    if m: return v + '.decode_' + m.group(1)
    m = re.match(r'io_(fcsr_rm|fcsr_flags_valid|fcsr_flags_bits|set_fs_dirty|csr_stall|exception|retire|cause|pc|tval|interrupt|interrupt_cause|evec|ptbr_mode|ptbr_ppn|status_prv|status_dprv|status_debug|status_mxr|status_sum)$', n)
    if m: return v + '.' + m.group(1)
    if n == 'io_singleStep': return v + '.single_step'
    # everything else: outputs left open, inputs tied to zero
    return '' if d == 'output' else "%d'b0" % width(w)

out.append('  %s u_csr (' % CSR)
out.append(',\n'.join('    .%s(%s)' % (n, csr_map(d, w, n)) for d, w, n in allp[CSR]))
out.append('  );\n')
open(os.path.join(ROOT, 'tb', 'boom_exe_dut_inst.svh'), 'w').write('\n'.join(out))

# unit -> which response ports / bypass ports actually exist (for the interface tie-offs)
caps = {}
for m, unit in UNITS.items():
    names = {n for d, w, n in allp[m]}
    caps[unit] = {
        'iresp': 'io_iresp_valid' in names, 'll_iresp': 'io_ll_iresp_valid' in names,
        'fresp': 'io_fresp_valid' in names, 'll_fresp': 'io_ll_fresp_valid' in names,
        'bypass': sum(1 for n in names if re.match(r'io_bypass_\d_valid', n)),
        'brinfo': 'io_brinfo_valid' in names, 'ftq': 'io_get_ftq_pc_pc' in names,
        'rs3': 'io_req_bits_rs3_data' in names, 'fcsr': 'io_fcsr_rm' in names,
    }
print(json.dumps(caps, indent=1))

# ----------------------------------------------------------------------------
# 3. file list
# ----------------------------------------------------------------------------
h = json.load(open(HIER))
roots = []
def find_all(n):
    if n['module_name'] in list(UNITS) + [IQ, CSR]: roots.append(n)
    for c in n['instances']: find_all(c)
find_all(h)
mods = set()
def collect(n):
    mods.add(n['module_name'])
    for c in n['instances']: collect(c)
for r in roots: collect(r)
with open(os.path.join(ROOT, 'dut', 'boom_exe_dut.f'), 'w') as f:
    f.write('// RTL subtree of ALUExeUnit_1 / ALUExeUnit_2 / FPUExeUnit / IssueUnitCollapsing_2 / CSRFile (%d modules)\n' % len(mods))
    for m in sorted(mods):
        f.write('${BOOM_RTL}/gen-collateral/%s.sv\n' % m)
print('dut modules:', len(mods))
